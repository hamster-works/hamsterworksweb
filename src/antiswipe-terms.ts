  const articleMatch = terms.match(/^# (?:Article 8|Artikel 8|Artículo 8|Articolo 8|Artigo 8|제8조|第8条|第8條|Статья 8)[^\n]*\n\n1\./m)
  if (!articleMatch || articleMatch.index === undefined) {
    throw new Error(`Could not find the localized privacy section for ${language}.`)
  }

  const firstItemStart = articleMatch.index + articleMatch[0].length - 2
  const searchStart = firstItemStart + 2
  const secondItemStart = terms.indexOf('2.', searchStart)
